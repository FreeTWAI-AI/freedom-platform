// Embeds the few canonical text files that platform routes serve, so neither the
// Node server nor the Cloudflare Worker reads the filesystem at request time.
// `node scripts/generate-runtime-text.mjs` rewrites the module; `--check` fails
// when it is stale. Edit the listed sources, never the generated module.
import {createHash} from 'node:crypto';
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

const root=new URL('../',import.meta.url);
const target='apps/platform-api/src/generated/runtime-text.ts';
export const runtimeTextSources={
  githubSocialCss:'apps/portal-web/src/modules/GitHubSocial.css',
  skillUploadSkillMarkdown:'packages/skill-upload-client/SKILL.md',
  skillUploadProtocolMarkdown:'packages/skill-upload-client/protocol.md',
};

export async function renderRuntimeText(){
  const lines=['// GENERATED by scripts/generate-runtime-text.mjs. Do not edit; change the source file and regenerate.',''];
  for(const [name,path] of Object.entries(runtimeTextSources)){
    const text=await readFile(new URL(path,root),'utf8');
    lines.push(`// ${path} sha256:${createHash('sha256').update(text).digest('hex')}`);
    lines.push(`export const ${name}=${JSON.stringify(text)};`);
  }
  return lines.join('\n')+'\n';
}

if(process.argv[1]===fileURLToPath(import.meta.url)){
  const expected=await renderRuntimeText(),path=new URL(target,root);
  if(process.argv.includes('--check')){
    const actual=await readFile(path,'utf8').catch(()=>'');
    if(actual!==expected){console.error(`${target} is stale. Run: npm run generate:runtime-text`);process.exit(1);}
  } else await writeFile(path,expected);
}
