test('all generated HTTP schemas and Zod reject caller authority and require exact bodies', () => {
  for (const profile of profiles) {
    const cases: Case[] = [{ name: 'valid minimal shape', value: profile.value, valid: true }];
    for (const value of [null, [], '', true, 1]) cases.push({ name: `non-object ${JSON.stringify(value)}`, value, valid: false });
    for (const field of Object.keys(profile.value)) {
      const incomplete = { ...profile.value }; delete incomplete[field];
      cases.push({ name: `missing ${field}`, value: incomplete, valid: false });
      cases.push({ name: `null ${field}`, value: { ...profile.value, [field]: null }, valid: false });
    }
    for (const field of ['key', 'actor', 'Actor', 'owner', 'ownerUserId', 'ownerPrincipalId', 'scopeId', 'expectedVersion',
      'expectedRunVersion', 'ttl', 'expiresAt', 'modelReady', 'model_ready', 'inferenceRef', 'token', 'accessToken',
      'providerEndpoint', 'secretRef', 'recoveryGeneration', 'operationalAuthority']) {
      cases.push({ name: `unknown authority ${field}`, value: { ...profile.value, [field]: 'synthetic' }, valid: false });
    }
    if (profile.name !== 'member-execution-http-run-metadata') {
      cases.push({ name: 'body cannot assert false authority', value: { ...profile.value, operational_authority: false }, valid: false });
    } else {
      cases.push({ name: 'response cannot grant authority', value: { ...profile.value, operational_authority: true }, valid: false });
    }
    for (const field of Object.keys(profile.value).filter(name => name.endsWith('Id'))) {
      for (const value of ['not-a-uuid', id.toUpperCase(), id + '\n', '12345678-1234-0234-8234-123456789abc',
        '12345678-1234-4234-1234-123456789abc', id.replaceAll('-', ''), 1]) {
        cases.push({ name: `invalid UUID ${field}: ${JSON.stringify(value)}`, value: { ...profile.value, [field]: value }, valid: false });
      }
    }
    parity(profile, cases);
  }
});

