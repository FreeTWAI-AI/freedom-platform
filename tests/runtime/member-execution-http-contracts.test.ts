test('nested selections remain explicit and reject wrong custody, defaults, secrets and owner fields', () => {
  const profile = profiles.find(item => item.name === 'member-execution-http-model-create')!;
  const cases: Case[] = [];
  const variants = [selection, { ...selection, credentialCustody: 'local_keychain', billingSource: 'user_byok' },
    { ...selection, credentialCustody: 'platform_vault', engineLocation: 'platform', billingSource: 'user_byok' }];
  for (const variant of variants) {
    cases.push({ name: `valid selection ${variant.credentialCustody}`, value: { connectionId: id, selection: variant }, valid: true });
    for (const field of Object.keys(variant)) {
      const incomplete = { ...variant } as Record<string, unknown>; delete incomplete[field];
      cases.push({ name: `missing ${variant.credentialCustody}.${field}`, value: { connectionId: id, selection: incomplete }, valid: false });
    }
    for (const field of ['owner', 'ownerPrincipalId', 'scopeId', 'actor', 'modelReady', 'operational_authority', 'inferenceRef',
      'fallback', 'secretRef', 'apiKey', 'authEvidence', 'localHandle', 'providerEndpoint']) {
      cases.push({ name: `nested unknown ${variant.credentialCustody}.${field}`, value: { connectionId: id,
        selection: { ...variant, [field]: false } }, valid: false });
    }
    for (const engineLocation of ['runtime_local', 'platform']) for (const billingSource of ['user_cli', 'user_byok', 'platform_system']) {
      const valid = variant.credentialCustody === 'official_cli' ? engineLocation === 'runtime_local' && billingSource === 'user_cli'
        : variant.credentialCustody === 'local_keychain' ? engineLocation === 'runtime_local' && billingSource === 'user_byok'
          : engineLocation === 'platform' && billingSource === 'user_byok';
      cases.push({ name: `binding ${variant.credentialCustody}/${engineLocation}/${billingSource}`,
        value: { connectionId: id, selection: { ...variant, engineLocation, billingSource } }, valid });
    }
  }
  for (const field of ['providerRef', 'modelRef', 'processingLocation']) {
    for (const value of ['', 'x'.repeat(97), 'x\n', 'https://synthetic.invalid', 'x y', null]) {
      cases.push({ name: `invalid label ${field}: ${JSON.stringify(value)}`,
        value: { connectionId: id, selection: { ...selection, [field]: value } }, valid: false });
    }
  }
  parity(profile, cases);
});

