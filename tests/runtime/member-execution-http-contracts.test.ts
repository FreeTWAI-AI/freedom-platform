const root = fileURLToPath(new URL('../../', import.meta.url));
const id = '12345678-1234-4234-8234-123456789abc';
const selection = { providerRef: 'synthetic-provider', modelRef: 'synthetic-model', processingLocation: 'provider_remote',
  artifactCustody: 'platform_asset', credentialCustody: 'official_cli', engineLocation: 'runtime_local', billingSource: 'user_cli' };
interface Case { name: string; value: unknown; valid: boolean }
interface Profile { name: string; schema: z.ZodType; value: Record<string, unknown> }
const profiles: Profile[] = [
  { name: 'member-execution-http-run-create', schema: MemberExecutionHttpRunCreateSchema, value: { workId: id } },
  { name: 'member-execution-http-empty', schema: MemberExecutionHttpEmptySchema, value: {} },
  { name: 'member-execution-http-model-create', schema: MemberExecutionHttpModelCreateSchema, value: { connectionId: id, selection } },
  { name: 'member-execution-http-grant-create', schema: MemberExecutionHttpGrantCreateSchema,
    value: { expectedWorkVersion: '1', connectionId: id, expectedConnectionVersion: '1', modelConnectionId: id, expectedModelVersion: '1', consent: true } },
  { name: 'member-execution-http-attempt-create', schema: MemberExecutionHttpAttemptCreateSchema, value: { grantId: id, expectedGrantVersion: '1' } },
  { name: 'member-execution-http-run-metadata', schema: MemberExecutionHttpRunMetadataSchema,
    value: { runId: id, workId: id, inputWorkVersion: '1', aggregateVersion: '1', state: 'created', taskLeaseEpoch: '1', controlEpoch: '1', operational_authority: false } },
];
function parity(profile: Profile, cases: Case[]) {
  for (const item of cases) assert.equal(profile.schema.safeParse(item.value).success, item.valid, `${profile.name}: ${item.name}`);
  const schema = JSON.parse(readFileSync(new URL(`../../contracts/execution/v1/${profile.name}.schema.json`, import.meta.url), 'utf8'));
  const script = `import json,sys
from jsonschema import Draft202012Validator,FormatChecker
payload=json.load(sys.stdin)
Draft202012Validator.check_schema(payload['schema'])
validator=Draft202012Validator(payload['schema'],format_checker=FormatChecker())
for case in payload['cases']:
    assert validator.is_valid(case['value']) == case['valid'], case['name']
print('conformant')`;
  const result = spawnSync('python3', ['-c', script], { cwd: root, env: verificationEnvironment(), encoding: 'utf8',
    input: JSON.stringify({ schema, cases }), timeout: 30000, maxBuffer: 128 * 1024 });
  assert.equal(result.status, 0, `${profile.name}\n${result.stdout}${result.stderr}`);
  assert.equal(result.stdout.trim(), 'conformant');
}

