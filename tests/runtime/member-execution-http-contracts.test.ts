test('HTTP configuration confines plaintext to explicit local loopback and rejects Hono HEAD before DB access', async () => {
  let queries = 0;
  const forbiddenPool = { query() { queries++; throw new Error('Unexpected database access.'); },
    connect() { queries++; throw new Error('Unexpected database access.'); } } as unknown as Pool;
  for (const environment of ['next', 'staging-next', 'local'] as const) {
    await assert.rejects(createMemberExecutionHttpTransport(forbiddenPool, {
      origin: 'http://synthetic.invalid', environment, clientId: 'synthetic-client',
    }), /invalid_member_execution_http_configuration/);
    if (environment !== 'local') {
      await assert.rejects(createMemberExecutionHttpTransport(forbiddenPool, {
        origin: 'http://127.0.0.1:4311', environment, clientId: 'synthetic-client',
      }), /invalid_member_execution_http_configuration/);
    }
  }
  for (const origin of ['http://localhost.evil.invalid', 'http://127.0.0.2', 'http://[::ffff:7f00:1]']) {
    await assert.rejects(createMemberExecutionHttpTransport(forbiddenPool, {
      origin, environment: 'local', clientId: 'synthetic-client',
    }), /invalid_member_execution_http_configuration/);
  }
  for (const origin of ['http://localhost:4311', 'http://127.0.0.1:4311', 'http://[::1]:4311', 'https://synthetic.invalid']) {
    const app = await createMemberExecutionHttpTransport(forbiddenPool, { origin, environment: 'local', clientId: 'synthetic-client' });
    for (const method of ['HEAD', 'OPTIONS', 'PUT']) {
      const response = await app.fetch(new Request(`${origin}/api/v1/me/execution-runs/${id}`, { method }));
      assert.equal(response.status, 405);
      assert.equal(response.headers.get('Allow'), 'GET');
      assert.equal(response.headers.get('Cache-Control'), 'private, no-store');
      assert.equal(response.headers.get('ETag'), null);
      if (method === 'HEAD') assert.equal(await response.text(), '');
    }
  }
  assert.equal(queries, 0, 'HEAD and unsupported methods must not reach charge/auth/record queries.');
});

test('shared HTTP reader preserves decoded-key, Unicode, byte, chunk and depth rejection boundaries', async () => {
  const request = (body: string | Uint8Array<ArrayBuffer>) => new Request('https://synthetic.invalid', {
    method: 'POST', headers: { 'Content-Type': 'application/json' }, body,
  });
  for (const body of ['{"connectionId":"x","\\u0063onnectionId":"y"}', '{"selection":{"x":1,"\\u0078":2}}',
    '{"\\u005f_proto__":1}', '{"constructor":1}', '{"prototype":1}', '{"x":"\\ud800"}', '{"x":1e0}',
    '{"x":-0}', '{"x":9007199254740992}', '\ufeff{}', '['.repeat(26) + ']'.repeat(26)]) {
    await assert.rejects(readBoundedHttpJson(request(body)), (error: unknown) => (error as {code?: string}).code === 'invalid_json');
  }
  for (const bytes of [new Uint8Array([0xc0, 0xaf]), new Uint8Array([0xed, 0xa0, 0x80]), new Uint8Array([0xf4, 0x90, 0x80, 0x80])]) {
    await assert.rejects(readBoundedHttpJson(request(bytes)), (error: unknown) => (error as {code?: string}).code === 'invalid_json');
  }
  assert.equal((await readBoundedHttpJson(request('{"x":"\\ud83d\\ude00"}')) as {x: string}).x, '😀');
  const streamed = (chunks: Uint8Array[]) => new Request('https://synthetic.invalid', {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: new ReadableStream<Uint8Array>({ start(controller) { for (const chunk of chunks) controller.enqueue(chunk); controller.close(); } }),
    duplex: 'half',
  } as RequestInit & {duplex: 'half'});
  const encoded = new TextEncoder().encode('{"x":"😀"}');
  assert.equal((await readBoundedHttpJson(streamed([...encoded].map(value => new Uint8Array([value])))) as {x: string}).x, '😀');
  const chunks = [new TextEncoder().encode('{'), ...Array.from({ length: 126 }, () => new Uint8Array()), new TextEncoder().encode('}')];
  assert.deepEqual(Object.keys(await readBoundedHttpJson(streamed(chunks)) as object), []);
  await assert.rejects(readBoundedHttpJson(streamed([...chunks, new Uint8Array()])),
    (error: unknown) => (error as {code?: string}).code === 'body_too_large');
});
